"""Optional E2E check: Python Playwright + /usr/bin/chromium, server already running."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':1100})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3000')
    expect(page.locator('h1')).to_contain_text('대시보드')
    page.screenshot(path='/tmp/gamedev-dashboard.png',full_page=True)
    page.get_by_role('link',name='5분 수준 진단').click()
    page.locator('#quiz-form button').click()
    expect(page.locator('#quiz-result')).to_be_empty()
    for i,answer in enumerate([1,1,0,1,1,1]):page.locator(f'input[name=q{i}][value="{answer}"]').check()
    page.locator('#quiz-form button').click()
    expect(page.locator('#quiz-result')).to_contain_text('6 / 6')
    page.reload()
    expect(page.locator('#quiz-result')).to_contain_text('6 / 6')
    page.locator('.nav-item[href="#problems"]').click()
    expect(page.locator('.problem-card')).to_have_count(19)
    page.locator('#search').fill('NGO')
    expect(page.locator('.problem-card')).to_have_count(1)
    page.locator('#search').fill('없는문제')
    expect(page.locator('.empty')).to_contain_text('검색 결과가 없습니다')
    page.locator('#search').fill('')
    page.get_by_role('button',name='입문',exact=True).click()
    expect(page.locator('.problem-card')).to_have_count(1)
    page.locator('.problem-card').click()
    source='public class PocketPractice { int n=4; public int WoodCount=>n; public bool TryPickUpWood(){if(n>=5)return false; n++; return true;} }'
    page.locator('#code').fill(source)
    page.locator('[data-field=approach]').fill('경계값부터 확인합니다.')
    page.reload()
    expect(page.locator('#code')).to_have_value(source)
    page.get_by_role('button',name='검증 결과',exact=True).click()
    expect(page.locator('.status-badge')).to_have_text('미검증')
    page.locator('#report-file').set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{}'})
    expect(page.locator('#toast')).to_contain_text('보고서가 필요합니다')
    page.locator('#run').click()
    expect(page.locator('.status-badge')).to_have_text('통과',timeout=75000)
    expect(page.locator('.test-list li')).to_have_count(3)
    expect(page.locator('.report-origin')).to_contain_text('로컬 .NET 실제 실행')
    page.get_by_role('button',name='풀이 작성',exact=True).click()
    page.locator('#code').fill(source.replace('n>=5','n>5'))
    page.locator('#run').click()
    expect(page.locator('.status-badge')).to_have_text('실패',timeout=75000)
    page.get_by_role('button',name='풀이 작성',exact=True).click()
    page.locator('#code').fill('invalid C#')
    page.locator('#run').click()
    expect(page.locator('#run-status')).to_contain_text('컴파일 또는 실행에 실패',timeout=75000)
    page.locator('#code').fill(source+' // edited')
    page.get_by_role('button',name='검증 결과',exact=True).click()
    expect(page.locator('.status-badge')).to_have_text('재검증 필요')
    page.locator('#submit').click()
    page.locator('.nav-item[href="#records"]').click()
    expect(page.locator('.record-row')).to_have_count(1)
    page.get_by_role('button',name='미리보기',exact=True).click()
    expect(page.locator('#preview-text')).to_contain_text('## 내 풀이 코드')
    expect(page.locator('#preview-text')).not_to_contain_text('경계값부터')
    with page.expect_download() as dl:page.locator('#preview-download').click()
    assert dl.value.suggested_filename=='pocket.md'
    assert '## 내 풀이 코드' in Path(dl.value.path()).read_text()
    page.locator('#close-dialog').click()
    with page.expect_download() as dl:page.locator('#backup').click()
    backup=json.loads(Path(dl.value.path()).read_text())
    page.locator('#restore').set_input_files({'name':'backup.json','mimeType':'application/json','buffer':json.dumps(backup).encode()})
    expect(page.locator('#toast')).to_contain_text('병합')
    expect(page.locator('.record-row')).to_have_count(1)
    page.goto('http://127.0.0.1:3000/#practice/events')
    page.get_by_role('button',name='검증 결과',exact=True).click()
    page.locator('#report-file').set_input_files({'name':'unity.xml','mimeType':'application/xml','buffer':b'<test-run><test-case fullname="Events.Reopen" result="Passed"/><test-case fullname="Events.Initial" result="Skipped"/></test-run>'})
    expect(page.locator('.status-badge')).to_have_text('일부 미실행')
    expect(page.locator('.report-origin')).to_contain_text('사용자 제공 외부 결과')
    page.locator('#report-file').set_input_files({'name':'empty.xml','mimeType':'application/xml','buffer':b'<test-run total="0"/>'})
    expect(page.locator('#toast')).to_contain_text('테스트가 없는 보고서')
    blocked=page.request.post('http://127.0.0.1:3000/api/grade',data={'source':'code','problemId':'pocket'})
    assert blocked.status==403
    project=page.request.get('http://127.0.0.1:3000/api/project').json()
    assert project['unityVersion']=='2022.3.62f3' and project['ngoPackage'] is None
    page.goto('http://127.0.0.1:3000/#project')
    expect(page.locator('.project-status')).to_contain_text('패키지 등록됨')
    with page.expect_download() as dl:page.locator('#commit-download').click()
    assert '검증:' in Path(dl.value.path()).read_text()
    for width in [390,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        for route in ['dashboard','problems','practice/pocket','diagnosis','records','roadmap','project']:
            page.goto('http://127.0.0.1:3000/#'+route)
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),(route,width,'horizontal overflow')
    page.set_viewport_size({'width':390,'height':900})
    page.goto('http://127.0.0.1:3000/#dashboard')
    page.screenshot(path='/tmp/gamedev-mobile.png',full_page=True)
    assert not errors,errors
    browser.close()
    print('PASS: actual C# run, failure/compiler error, draft/quiz persistence, filters, reports, Unity XML, stale code, history, Markdown, backup/restore, commit download, project API, 7 routes at 3 sizes; no JS errors.')
